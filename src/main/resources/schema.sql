CREATE TABLE IF NOT EXISTS STUDENTS (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(15) NOT NULL, surname VARCHAR(25) NOT NULL,
 faculty VARCHAR(20) NOT NULL, age INTEGER NOT NULL CHECK (age BETWEEN 0 AND 150)
);
CREATE TABLE IF NOT EXISTS STUDY_GROUPS (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(30) NOT NULL, faculty VARCHAR(50) NOT NULL,
 curator VARCHAR(100) NOT NULL, course INTEGER NOT NULL CHECK (course BETWEEN 1 AND 6)
);